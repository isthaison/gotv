import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '../..');
const wasmOutPath = path.resolve(rootDir, 'site/gotv.wasm');
const base64OutPath = path.resolve(rootDir, 'web/src/engine/gotvWasmBase64.ts');

console.log('🔨 Compiling GoTV pure C core to WebAssembly (WASM)...');

const compileCmd = [
  'clang',
  '--target=wasm32',
  '-O3',
  '-nostdlib',
  '-Wl,--no-entry',
  '-Wl,--export-all',
  '-Iengine/wasm',
  '-Iengine',
  'engine/wasm/glib_shim.c',
  'engine/charset.c',
  'engine/compose.c',
  'engine/phonology.c',
  'engine/promotion.c',
  'engine/spell.c',
  'engine/wasm/gotv_wasm.c',
  '-o',
  wasmOutPath,
].join(' ');

try {
  execSync('clang --version', { stdio: 'ignore' });
} catch {
  if (fs.existsSync(base64OutPath)) {
    console.log('⚠️ clang not found, but pre-built gotvWasmBase64.ts exists. Skipping WASM compilation.');
    process.exit(0);
  }
}

try {
  execSync(compileCmd, { cwd: rootDir, stdio: 'inherit' });
  console.log(`✅ Compiled successfully to: ${wasmOutPath}`);

  // Also copy to web/gotv.wasm
  fs.copyFileSync(wasmOutPath, path.resolve(rootDir, 'web/gotv.wasm'));

  // Generate Base64 module
  const wasmBuffer = fs.readFileSync(wasmOutPath);
  const b64 = wasmBuffer.toString('base64');
  const fileContent = `// Auto-generated by web/scripts/build-wasm.js
// Pure C core compiled to WebAssembly (18KB)
export const GOTV_WASM_BASE64 = "${b64}";
`;
  fs.writeFileSync(base64OutPath, fileContent, 'utf-8');
  console.log(`✅ Generated base64 module: ${base64OutPath} (${(wasmBuffer.length / 1024).toFixed(1)} KB)`);
} catch (err) {
  console.error('❌ Failed to compile C to WASM:', err);
  process.exit(1);
}
